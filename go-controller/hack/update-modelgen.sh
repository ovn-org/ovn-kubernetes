set -o errexit
set -o nounset
set -o pipefail

# generate ovsdb bindings
if  ! ( command -v modelgen > /dev/null ); then
  echo "modelgen not found, installing github.com/ovn-kubernetes/libovsdb/cmd/modelgen"
  olddir="${PWD}"
  builddir="$(mktemp -d)"
  cd "${builddir}"
  # ensure the hash value is not outdated, if wrong bindings are being generated re-install modelgen
  GO111MODULE=on go install github.com/ovn-kubernetes/libovsdb/cmd/modelgen@v0.9.0
  cd "${olddir}"
  if [[ "${builddir}" == /tmp/* ]]; then #paranoia
      rm -rf "${builddir}"
  fi
fi

go generate ./pkg/nbdb
go generate ./pkg/sbdb
go generate ./pkg/vswitchd

# modelgen owns its generated-code header and does not provide a way to add a
# project-specific license header. Restore our standard header after generation.
while IFS= read -r -d '' file; do
  if [[ "$(head -n 1 "${file}")" == '// Code generated by "libovsdb.modelgen"' ]]; then
    tmp="$(mktemp "${file}.tmp.XXXXXX")"
    {
      cat hack/boilerplate.go.txt
      echo
      cat "${file}"
    } > "${tmp}"
    chmod --reference="${file}" "${tmp}"
    mv "${tmp}" "${file}"
  fi
done < <(find pkg/nbdb pkg/sbdb pkg/vswitchd -type f -name '*.go' -print0)
